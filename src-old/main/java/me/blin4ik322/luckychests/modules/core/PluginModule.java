package me.blin4ik322.luckychests.modules.core;

import org.bukkit.plugin.java.JavaPlugin;

/**
 * Общий интерфейс для функциональных модулей плагина.
 *
 * Каждая фича — это отдельный модуль в своей папке (например, modules/automelter),
 * реализующий этот интерфейс. Модуль сам инкапсулирует свои слушатели,
 * команды и состояние — основной класс плагина ничего не знает о деталях.
 */
public interface PluginModule {

    /**
     * Регистрирует всё, что нужно модулю: слушатели событий, команды, задачи и т.д.
     * Вызывается один раз при старте плагина, из ModuleManager.loadAll().
     */
    void load(JavaPlugin plugin);

    /**
     * Короткое имя модуля — используется только для логов при загрузке.
     */
    String getName();
}